const encode=value=>new TextEncoder().encode(typeof value==='string'?value:JSON.stringify(value)).buffer;
const hash=bytes=>createHash('sha256').update(Buffer.from(bytes)).digest('hex');
const line={type:'LineString',coordinates:[[40.02,43.05],[40.08,43.05]]};
const fixture=(payload=line)=>{const bytes=encode(payload),sha256=hash(bytes),url='/data/routes/checked.geojson';return{bytes,sha256,url,sources:{'routes/checked.geojson':sha256},versioned:`${url}?v=${sha256.slice(0,16)}`};};
const deferred=()=>{let resolve,reject;const promise=new Promise((yes,no)=>{resolve=yes;reject=no;});return{promise,resolve,reject};};
const waitFor=async predicate=>{const deadline=Date.now()+3000;while(!predicate()&&Date.now()<deadline)await new Promise(done=>setTimeout(done,1));assert.ok(predicate(),'Expected asynchronous source verification state did not settle');};

test('selected route uses exact generated bytes, a content version and the caller cancellation signal',async()=>{
  const payload={type:'FeatureCollection',features:[{type:'Feature',properties:{name:'Проверенная линия'},geometry:line}]},source=fixture(payload),controller=new AbortController(),reads=[],invalidated=[];
  assert.deepEqual(versionedRouteSource(source.url,source.sources),{url:source.versioned,sha256:source.sha256});
  const geometry=await loadVerifiedRouteGeometry(source.url,source.sources,{
    signal:controller.signal,load:async(url,priority,signal)=>{reads.push({url,priority,signal});return source.bytes;},invalidate:url=>invalidated.push(url),
  });
  assert.deepEqual(geometry,payload);assert.deepEqual(reads,[{url:source.versioned,priority:0,signal:controller.signal}]);assert.deepEqual(invalidated,[]);
});

test('stale valid geometry fails the selected-source hash and invalidates only the versioned resource',async()=>{
  const source=fixture(),reads=[],invalidated=[],stale=encode({...line,coordinates:[[40.02,43.05],[41.08,43.05]]});
  await assert.rejects(loadVerifiedRouteGeometry(source.url,source.sources,{
    signal:new AbortController().signal,load:async url=>{reads.push(url);return stale;},invalidate:url=>invalidated.push(url),
  }),/integrity mismatch/);
  assert.deepEqual(reads,[source.versioned]);assert.deepEqual(invalidated,[source.versioned]);assert.ok(!invalidated.includes(source.url));
  const restored=await loadVerifiedRouteGeometry(source.url,source.sources,{
    signal:new AbortController().signal,load:async url=>{reads.push(url);return source.bytes;},invalidate:url=>invalidated.push(url),
  });
  assert.deepEqual(restored,line);assert.deepEqual(reads,[source.versioned,source.versioned]);assert.equal(invalidated.length,1);
});

