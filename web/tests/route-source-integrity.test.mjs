test('source lookup rejects foreign URLs, path traversal, query aliases, absent hashes and inherited keys',async()=>{
  const source=fixture();
  for(const url of ['https://other.invalid/data/routes/checked.geojson','//other.invalid/data/routes/checked.geojson','data/routes/checked.geojson','/routes/checked.geojson','/data/../routes/checked.geojson','/data/routes/../checked.geojson','/data/routes/%2e%2e/checked.geojson','/data/routes\\checked.geojson','/data//routes/checked.geojson',source.url+'?v=old',source.url+'#fragment','/data/routes/unknown.geojson']){
    const key=url.startsWith('/data/')?url.slice('/data/'.length):url;
    const hashes={...source.sources,...(url.endsWith('unknown.geojson')?{}:{[key]:source.sha256})};
    assert.throws(()=>versionedRouteSource(url,hashes),/absent from the current catalogue/,url);
  }
  for(const sha256 of ['',source.sha256.slice(1),source.sha256.toUpperCase(),'g'.repeat(64)])assert.throws(()=>versionedRouteSource(source.url,{'routes/checked.geojson':sha256}),/absent/);
  assert.throws(()=>versionedRouteSource(source.url,Object.create(source.sources)),/absent/);
  let reads=0;
  await assert.rejects(loadVerifiedRouteGeometry(source.url,{}, {signal:new AbortController().signal,load:async()=>{reads++;return source.bytes;},invalidate:()=>assert.fail('Invalid lookup must not invalidate a resource')}),/absent/);
  assert.equal(reads,0);
});

test('cancelled reads reject before parsing and leave other consumers cached bytes alone',async()=>{
  const source=fixture(),controller=new AbortController(),reason=new Error('selection replaced'),pending=deferred(),invalidated=[];let reads=0;
  controller.abort(reason);
  await assert.rejects(loadVerifiedRouteGeometry(source.url,source.sources,{
    signal:controller.signal,load:async()=>{reads++;return source.bytes;},invalidate:url=>invalidated.push(url),
  }),error=>error===reason);assert.equal(reads,0);
  const current=new AbortController(),request=loadVerifiedRouteGeometry(source.url,source.sources,{
    signal:current.signal,load:async(_url,_priority,signal)=>{assert.equal(signal,current.signal);return pending.promise;},invalidate:url=>invalidated.push(url),
  });
  const rejected=assert.rejects(request,error=>error===reason);
  current.abort(reason);pending.resolve(encode('invalid stale body'));await rejected;assert.deepEqual(invalidated,[]);
});

test('cancellation during digest cannot invalidate the shared source or prevent another consumer completing',async t=>{
  const source=fixture(),digest=await globalThis.crypto.subtle.digest('SHA-256',source.bytes),gates=[],invalidated=[],controller=new AbortController(),other=new AbortController(),reason=new Error('map closed');
  t.mock.method(globalThis.crypto.subtle,'digest',(algorithm,bytes)=>{
    assert.equal(algorithm,'SHA-256');assert.equal(bytes,source.bytes);const gate=deferred();gates.push(gate);return gate.promise;
  });
  const options=signal=>({signal,load:async()=>source.bytes,invalidate:url=>invalidated.push(url)});
  const cancelled=loadVerifiedRouteGeometry(source.url,source.sources,options(controller.signal)),accepted=loadVerifiedRouteGeometry(source.url,source.sources,options(other.signal));
  const rejected=assert.rejects(cancelled,error=>error===reason);
  await waitFor(()=>gates.length===2);controller.abort(reason);gates.forEach(gate=>gate.resolve(digest));
  await rejected;assert.deepEqual(await accepted,line);assert.deepEqual(invalidated,[]);assert.equal(other.signal.aborted,false);
});

